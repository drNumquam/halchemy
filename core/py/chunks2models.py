def normalize_title(value: str) -> str:
    """Normalize titles for a conservative fallback match."""

    value = re.sub(r"\s+", " ", value).strip().casefold()
    return value.rstrip(".:")


def match_ranked_sections(
    ranked: list[RankedSection],
    document_sections: dict[str, DocumentSection],
) -> tuple[list[tuple[RankedSection, DocumentSection]], list[RankedSection]]:
    """Match primarily by SEC ID, then by a unique normalized title."""

    title_index: dict[str, list[DocumentSection]] = {}
    for section in document_sections.values():
        title_index.setdefault(normalize_title(section.title), []).append(section)

    matched: list[tuple[RankedSection, DocumentSection]] = []
    missing: list[RankedSection] = []

    for ranked_section in ranked:
        document_section = document_sections.get(ranked_section.section_id)

        if document_section is not None:
            if normalize_title(document_section.title) != normalize_title(
                ranked_section.title
            ):
                candidates = title_index.get(normalize_title(ranked_section.title), [])
                if len(candidates) == 1:
                    document_section = candidates[0]
                else:
                    document_section = None
        else:
            candidates = title_index.get(normalize_title(ranked_section.title), [])
            document_section = candidates[0] if len(candidates) == 1 else None

        if document_section is None:
            missing.append(ranked_section)
        else:
            matched.append((ranked_section, document_section))

    return matched, missing


