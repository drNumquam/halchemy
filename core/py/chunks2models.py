REF_PATTERN = re.compile(r"^#/(?P<collection>[^/]+)/(?P<index>\d+)$")


def reference_string(value: Any) -> str | None:
    """Return a Docling JSON reference string from a reference-like value."""

    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        raw = value.get("$ref")
        return raw if isinstance(raw, str) else None
    return None


def resolve_reference(document: dict[str, Any], ref: str) -> dict[str, Any] | None:
    """Resolve references such as '#/texts/42' in a raw Docling document."""

    match = REF_PATTERN.match(ref)
    if not match:
        return None

    collection = document.get(match.group("collection"))
    if not isinstance(collection, list):
        return None

    index = int(match.group("index"))
    if index < 0 or index >= len(collection):
        return None

    item = collection[index]
    return item if isinstance(item, dict) else None


def iter_body_items(document: dict[str, Any]) -> Iterator[dict[str, Any]]:
    """
    Yield BODY items in Docling tree order.

    Groups are structural containers and are not yielded. A visited set avoids
    duplicate emission if an item is referenced more than once.
    """

    body = document.get("body", {})
    root_children = body.get("children", []) if isinstance(body, dict) else []
    visited: set[str] = set()

    def walk_reference(ref: str) -> Iterator[dict[str, Any]]:
        if ref in visited:
            return
        visited.add(ref)

        item = resolve_reference(document, ref)
        if item is None:
            return

        label = str(item.get("label", ""))
        if label == "group":
            for child in item.get("children", []):
                child_ref = reference_string(child)
                if child_ref:
                    yield from walk_reference(child_ref)
            return

        if item.get("content_layer") == "body":
            yield item

        # Captions and list children may be nested below semantic items.
        for child in item.get("children", []):
            child_ref = reference_string(child)
            if child_ref:
                yield from walk_reference(child_ref)

    for child in root_children:
        child_ref = reference_string(child)
        if child_ref:
            yield from walk_reference(child_ref)


