def section_page_span(section: DocumentSection, fallback: str) -> str:
    pages = sorted(section.touched_pages)
    if not pages:
        return fallback
    if len(pages) == 1:
        return str(pages[0])
    return f"{pages[0]}-{pages[-1]}"


def markdown_list(values: list[str], empty_text: str = "None") -> str:
    if not values:
        return empty_text
    return "\n\n".join(values)


def build_section_chunk(
    ranked: RankedSection,
    section: DocumentSection,
) -> str:
    """Build the complete section-only Markdown context for the AI agent."""

    hierarchy = " > ".join(section.hierarchy) if section.hierarchy else "None"
    table_blocks: list[str] = []
    for index, table in enumerate(section.tables_markdown, start=1):
        caption = (
            section.table_captions[index - 1]
            if index - 1 < len(section.table_captions)
            else None
        )
        parts = [f"### Table {index}"]
        if caption:
            parts.append(f"**Caption:** {caption}")
        parts.append(table)
        table_blocks.append("\n\n".join(parts))

    image_caption_lines = [f"- {caption}" for caption in section.image_captions]
    footnote_lines = [f"> {footnote}" for footnote in section.footnotes]

    return f"""# SECTION

- ID: {ranked.section_id}
- Title: {ranked.title}
- Hierarchy: {hierarchy}
- Ranked pages: {ranked.pages}
- Reconstructed pages: {section_page_span(section, ranked.pages)}
- Confidence: {ranked.confidence:.2f}

## TEXT

{markdown_list(section.text_blocks)}

## TABLES

{markdown_list(table_blocks)}

## TABLE CAPTIONS

{markdown_list([f'- {value}' for value in section.table_captions])}

## IMAGE CAPTIONS

{markdown_list(image_caption_lines)}

## FOOTNOTES

{markdown_list(footnote_lines)}
""".strip()


def build_agent_prompt(
    template_text: str,
    chunk: str,
    validation_error: str | None = None,
) -> str:
    """Build the user message while leaving domain instructions to --prompt."""

    correction = ""
    if validation_error:
        correction = f"""

PREVIOUS RESPONSE VALIDATION ERROR

{validation_error}

Correct the output. Return the complete YAML document again.
"""

    return f"""Populate the YAML template using only evidence contained in the section chunk.

Mandatory rules:
- Preserve the template's root type and all existing mapping keys.
- Do not invent unsupported values.
- Leave unknown scalar values null or empty, consistently with the template.
- Return only the complete valid YAML document.
- Do not use Markdown fences, commentary, analysis, or explanatory prose.

YAML TEMPLATE

{template_text}

SECTION CHUNK

{chunk}{correction}
""".strip()


