RANK_LINE_PATTERN = re.compile(
    r"^\s*\[(?P<id>[A-Za-z0-9_-]+)\]\t"
    r"(?P<title>.*?)\t"
    r"\((?P<pages>.*?)\)\t"
    r"(?P<confidence>(?:0(?:\.\d+)?|1(?:\.0+)?))\s*$"
)


def load_ranked_sections(
    path: Path,
    confidence_min: float,
) -> tuple[list[RankedSection], int]:
    """Read toc_ranked.tsv and retain rows at or above the threshold."""

    all_count = 0
    selected: list[RankedSection] = []

    for line_number, raw_line in enumerate(
        path.read_text(encoding="utf-8").splitlines(), start=1
    ):
        if not raw_line.strip():
            continue

        match = RANK_LINE_PATTERN.match(raw_line)
        if not match:
            raise ValueError(
                f"Invalid ranked TSV line {line_number} in '{path}':\n"
                f"{raw_line}\n"
                "Expected: [SEC_xxxx]<TAB>Title<TAB>(pages)<TAB>confidence"
            )

        all_count += 1
        confidence = float(match.group("confidence"))
        if confidence < confidence_min:
            continue

        selected.append(
            RankedSection(
                section_id=match.group("id").strip(),
                title=match.group("title").strip(),
                pages=match.group("pages").strip(),
                confidence=confidence,
                rank=all_count,
            )
        )

    return selected, all_count


