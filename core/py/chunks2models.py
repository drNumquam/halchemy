BULLET_PATTERN = re.compile(r"^[·•\-*]\s+")
NOISE_HEADING_PATTERN = re.compile(
    r"^(?:Where:|(?:Notes?|Notices?|Caution|Warning|Important)\s*[:：]|"
    r"(?:Table\s+\d+\.|Figure\s+\d+\.|Equation\s+\d+:))",
    re.IGNORECASE,
)


def clean_heading_text(raw_title: str) -> str:
    """Apply the same heading cleanup used by pdf2toc.py."""

    cleaned = re.sub(r"^[^\w\s\(\)\[\]]+\s*", "", raw_title.strip())
    return cleaned.strip()


def item_page(item: dict[str, Any]) -> int | None:
    """Return the first 1-based Docling page number attached to an item."""

    provenance = item.get("prov")
    if not isinstance(provenance, list) or not provenance:
        return None
    page_no = provenance[0].get("page_no")
    return page_no if isinstance(page_no, int) else None


def item_text(item: dict[str, Any]) -> str:
    value = item.get("text", "")
    return value.strip() if isinstance(value, str) else ""


def referenced_texts(
    document: dict[str, Any],
    references: Any,
) -> list[str]:
    """Resolve caption/footnote references and return unique text values."""

    if not isinstance(references, list):
        return []

    values: list[str] = []
    for value in references:
        ref = reference_string(value)
        if not ref:
            continue
        resolved = resolve_reference(document, ref)
        if resolved is None:
            continue
        text = item_text(resolved)
        if text and text not in values:
            values.append(text)
    return values


def escape_markdown_cell(value: Any) -> str:
    """Normalize a value for a Markdown table cell."""

    text = "" if value is None else str(value)
    text = re.sub(r"\s+", " ", text).strip()
    return text.replace("|", r"\|")


def table_to_markdown(table_item: dict[str, Any]) -> str:
    """Convert Docling table grid data to a Markdown table."""

    data = table_item.get("data", {})
    if not isinstance(data, dict):
        return ""

    grid = data.get("grid")
    if isinstance(grid, list) and grid:
        rows: list[list[str]] = []
        max_columns = 0

        for raw_row in grid:
            if not isinstance(raw_row, list):
                continue
            row = [
                escape_markdown_cell(cell.get("text", ""))
                if isinstance(cell, dict)
                else escape_markdown_cell(cell)
                for cell in raw_row
            ]
            rows.append(row)
            max_columns = max(max_columns, len(row))

        if rows and max_columns:
            rows = [row + [""] * (max_columns - len(row)) for row in rows]
            header = rows[0]
            body = rows[1:]
            lines = [
                "| " + " | ".join(header) + " |",
                "| " + " | ".join(["---"] * max_columns) + " |",
            ]
            lines.extend("| " + " | ".join(row) + " |" for row in body)
            return "\n".join(lines)

    # Fallback for documents lacking the precomputed grid.
    num_rows = int(data.get("num_rows", 0) or 0)
    num_cols = int(data.get("num_cols", 0) or 0)
    cells = data.get("table_cells", [])
    if num_rows <= 0 or num_cols <= 0 or not isinstance(cells, list):
        return ""

    matrix = [["" for _ in range(num_cols)] for _ in range(num_rows)]
    for cell in cells:
        if not isinstance(cell, dict):
            continue
        row = int(cell.get("start_row_offset_idx", 0) or 0)
        col = int(cell.get("start_col_offset_idx", 0) or 0)
        if 0 <= row < num_rows and 0 <= col < num_cols:
            matrix[row][col] = escape_markdown_cell(cell.get("text", ""))

    lines = [
        "| " + " | ".join(matrix[0]) + " |",
        "| " + " | ".join(["---"] * num_cols) + " |",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in matrix[1:])
    return "\n".join(lines)


def collect_footnotes_by_page(document: dict[str, Any]) -> dict[int, list[str]]:
    """Collect explicit Docling footnotes by page."""

    result: dict[int, list[str]] = {}
    for text_item in document.get("texts", []):
        if not isinstance(text_item, dict) or text_item.get("label") != "footnote":
            continue
        page = item_page(text_item)
        text = item_text(text_item)
        if page is not None and text:
            result.setdefault(page, [])
            if text not in result[page]:
                result[page].append(text)
    return result


def append_unique(target: list[str], values: list[str]) -> None:
    """Append non-empty strings while preserving order and uniqueness."""

    for value in values:
        clean = value.strip()
        if clean and clean not in target:
            target.append(clean)


def reconstruct_sections(document: dict[str, Any]) -> dict[str, DocumentSection]:
    """
    Reconstruct SEC_xxxx sections using pdf2toc-compatible heading rules.

    Content is assigned to the active section until the next accepted section
    header. Captions linked to tables and pictures remain attached to those
    objects. Explicit page footnotes are propagated to every section touching
    that page, matching pdf2toc.py behavior.
    """

    sections: dict[str, DocumentSection] = {}
    current: DocumentSection | None = None
    section_counter = 0
    heading_stack: list[tuple[int, str]] = []
    footnotes_by_page = collect_footnotes_by_page(document)

    def create_section(title: str, level: int, page: int | None) -> DocumentSection:
        nonlocal section_counter

        while heading_stack and heading_stack[-1][0] >= level:
            heading_stack.pop()
        hierarchy = [entry_title for _, entry_title in heading_stack]

        section = DocumentSection(
            section_id=f"SEC_{section_counter:04d}",
            title=title,
            level=level,
            page_start=page,
            hierarchy=hierarchy,
        )
        section_counter += 1
        if page is not None:
            section.touched_pages.add(page)
        heading_stack.append((level, title))
        return section

    def ensure_current(page: int | None) -> DocumentSection:
        nonlocal current
        if current is None:
            current = create_section("Preamble / Initial Content", 1, page)
        return current

    for item in iter_body_items(document):
        label = str(item.get("label", ""))
        page = item_page(item)
        text = item_text(item)

        if label == "footnote":
            continue

        if label == "section_header":
            raw_text = text
            if BULLET_PATTERN.match(raw_text):
                active = ensure_current(page)
                bullet_label = BULLET_PATTERN.sub("", raw_text).strip()
                if bullet_label:
                    active.text_blocks.append(f"- **{bullet_label}**")
                if page is not None:
                    active.touched_pages.add(page)
                continue

            clean_title = clean_heading_text(raw_text)
            if NOISE_HEADING_PATTERN.match(clean_title):
                active = ensure_current(page)
                if clean_title:
                    active.text_blocks.append(f"**{clean_title}**")
                if page is not None:
                    active.touched_pages.add(page)
                continue

            if current is not None:
                sections[current.section_id] = current

            raw_level = item.get("level")
            level = max(1, raw_level if isinstance(raw_level, int) else 1)
            current = create_section(clean_title, level, page)
            continue

        active = ensure_current(page)
        if page is not None:
            active.touched_pages.add(page)

        if label in {"text", "paragraph", "list_item", "formula", "code"}:
            if text:
                if label == "list_item" and not re.match(r"^[-*+]\s", text):
                    text = f"- {text}"
                active.text_blocks.append(text)

        elif label == "table":
            caption_values = referenced_texts(document, item.get("captions"))
            append_unique(active.table_captions, caption_values)
            append_unique(
                active.footnotes,
                referenced_texts(document, item.get("footnotes")),
            )
            markdown = table_to_markdown(item)
            if markdown:
                active.tables_markdown.append(markdown)

        elif label == "picture":
            append_unique(
                active.image_captions,
                referenced_texts(document, item.get("captions")),
            )
            append_unique(
                active.footnotes,
                referenced_texts(document, item.get("footnotes")),
            )
            image = item.get("image")
            if isinstance(image, dict):
                uri = image.get("uri")
                if isinstance(uri, str) and uri and uri not in active.image_uris:
                    active.image_uris.append(uri)

        elif label == "caption":
            # Linked captions are already attached to their table/picture.
            parent_ref = reference_string(item.get("parent"))
            if not parent_ref and text:
                active.image_captions.append(text)

    if current is not None:
        sections[current.section_id] = current

    for section in sections.values():
        for page in sorted(section.touched_pages):
            append_unique(section.footnotes, footnotes_by_page.get(page, []))

    return sections


