"""
CONTRACT & SPECIFICATION
======================
Script: ranks2chunks.py
Purpose: Filter sections from toc_ranked.tsv with confidence >= --confidence_min,
         retrieve their full content from the Docling JSON created by pdf2toc.py,
         and invoke an AI agent to:
           1) Link valid page footnotes and captions to the proper section.
           2) Resolve structural and semantic cross-references to other sections
              in the JSON (excluding listing/index sections), computing/assigning
              confidence scores for referenced sections as well.
         Outputs chunks.tsv (all starting IDs + referenced IDs) and a report log.

CLI Syntax:
  python ranks2chunks.py --ranked_toc <path_to_toc_ranked.tsv>
                         --json <path_to_docling.json>
                         --confidence_min <0.0-0.99>
                         --prompt <path_to_ranks2chunks_prompt.txt>
                         --output <path_to_chunks.tsv_or_dir>
                         [--concurrent <1-4>]

Arguments:
  --ranked_toc     (Required) Path to toc_ranked.tsv generated by toc2ranks.py.
  --json           (Required) Path to JSON file generated by pdf2toc.py.
  --confidence_min (Required) Minimum confidence threshold (float in [0.0, 0.99]).
  --prompt         (Required) Path to system prompt file (default: ranks2chunks_prompt.txt).
  --output         (Required) Path to output chunks.tsv file or directory (default: chunks.tsv).
  --concurrent     (Optional) Max concurrent LLM requests, 1 to 4 (default: 1).

Dependencies:
  - Python >= 3.10
  - Standard library: argparse, asyncio, io, json, os, re, sys, contextlib, pathlib
  - Third-party: docling-core (DoclingDocument, ContentLayer, DocItemLabel, ...)
  - Third-party (for LLM_PROVIDER="qwen"): openai, httpx
  - Third-party (for LLM_PROVIDER="copilot"): copilot (CopilotClient)

Outputs (saved in the target directory):
  1. chunks.tsv               : Deduplicated list of starting + referenced section IDs
                                Format: [<id>]\t<title>\t(<pages>)\t<conf>\t[<TAG>]
  2. <script_stem>_report.txt : Console output log (overwritten at every run)
"""

