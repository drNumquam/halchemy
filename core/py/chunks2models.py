class Tee(io.TextIOBase):
    """Mirror writes to a console stream and a report file."""

    def __init__(self, console_stream, file_stream):
        self.console_stream = console_stream
        self.file_stream = file_stream

    @property
    def encoding(self):
        return getattr(self.console_stream, "encoding", "utf-8")

    def isatty(self) -> bool:
        return bool(
            hasattr(self.console_stream, "isatty")
            and self.console_stream.isatty()
        )

    def write(self, text: str) -> int:
        if not text:
            return 0
        self.console_stream.write(text)
        self.console_stream.flush()
        if not self.file_stream.closed:
            self.file_stream.write(text)
            self.file_stream.flush()
        return len(text)

    def flush(self) -> None:
        self.console_stream.flush()
        if not self.file_stream.closed:
            self.file_stream.flush()


@contextmanager
def tee_output_to_file(report_path: Path):
    """Mirror stdout and stderr to report_path for the context duration."""

    report_path.parent.mkdir(parents=True, exist_ok=True)
    original_stdout = sys.stdout
    original_stderr = sys.stderr

    with report_path.open("w", encoding="utf-8") as report_file:
        sys.stdout = Tee(original_stdout, report_file)
        sys.stderr = Tee(original_stderr, report_file)
        try:
            yield report_path
        finally:
            sys.stdout = original_stdout
            sys.stderr = original_stderr


