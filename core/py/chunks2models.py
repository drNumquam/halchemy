def validate_structure(template: Any, result: Any, path: str = "$" ) -> None:
    """Ensure mappings retain template keys and root/container types."""

    if isinstance(template, dict):
        if not isinstance(result, dict):
            raise ValueError(f"{path} must be a YAML mapping.")
        missing = [key for key in template if key not in result]
        if missing:
            raise ValueError(f"{path} is missing template keys: {missing}")
        for key, template_value in template.items():
            validate_structure(template_value, result[key], f"{path}.{key}")
        return

    if isinstance(template, list):
        if not isinstance(result, list):
            raise ValueError(f"{path} must be a YAML sequence.")
        if template and result:
            for index, value in enumerate(result):
                validate_structure(template[0], value, f"{path}[{index}]")


def parse_and_validate_yaml(content: str, template_data: Any) -> Any:
    """Parse LLM output and validate it against the template structure."""

    if not content.strip():
        raise ValueError("The model returned an empty response.")
    try:
        parsed = yaml.safe_load(content)
    except yaml.YAMLError as exc:
        raise ValueError(f"Invalid YAML: {exc}") from exc
    if parsed is None:
        raise ValueError("The model returned an empty YAML document.")
    validate_structure(template_data, parsed)
    return parsed


def save_yaml(path: Path, parsed: Any) -> None:
    """Serialize validated YAML predictably and overwrite the target."""

    path.write_text(
        yaml.safe_dump(
            parsed,
            allow_unicode=True,
            sort_keys=False,
            default_flow_style=False,
        ),
        encoding="utf-8",
    )


async def generate_section_model(
    ranked: RankedSection,
    section: DocumentSection,
    system_prompt: str,
    template_text: str,
    template_data: Any,
    model_name: str,
    output_dir: Path,
    copilot_session=None,
) -> tuple[str, bool, str | None]:
    """Generate and validate one section model, with corrective retries."""

    section_id = ranked.section_id
    output_path = output_dir / f"{section_id}.yaml"
    chunk = build_section_chunk(ranked, section)
    validation_error: str | None = None

    print(
        f"  [{section_id}] Start | confidence={ranked.confidence:.2f} | "
        f"title={ranked.title}"
    )

    for attempt in range(1, MAX_YAML_ATTEMPTS + 1):
        try:
            user_prompt = build_agent_prompt(
                template_text,
                chunk,
                validation_error=validation_error,
            )
            raw_response = await call_llm(
                system_prompt,
                user_prompt,
                model_name,
                copilot_session,
            )
            parsed = parse_and_validate_yaml(raw_response, template_data)
            save_yaml(output_path, parsed)
            print(f"  [{section_id}] SUCCESS -> {output_path.name}")
            return section_id, True, None
        except Exception as exc:  # Retry model, transport and validation failures.
            validation_error = str(exc)
            if attempt < MAX_YAML_ATTEMPTS:
                print(
                    f"  [{section_id}] Attempt {attempt}/{MAX_YAML_ATTEMPTS} "
                    f"failed: {validation_error}. Retrying..."
                )
            else:
                print(
                    f"  [{section_id}] FAILED after {MAX_YAML_ATTEMPTS} "
                    f"attempts: {validation_error}"
                )

    return section_id, False, validation_error


