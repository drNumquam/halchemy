def init_llm_client() -> str:
    """Initialize the same provider logic used by toc2ranks.py."""

    global client

    if LLM_PROVIDER == "qwen":
        import httpx
        from openai import OpenAI

        client = OpenAI(
            base_url=QWEN_BASE_URL,
            api_key="lm-studio",
            timeout=600.0,
            http_client=httpx.Client(trust_env=False, timeout=600.0),
        )
        return QWEN_MODEL_NAME

    if LLM_PROVIDER == "copilot":
        return COPILOT_MODEL_NAME

    raise ValueError(f"Unsupported LLM_PROVIDER: {LLM_PROVIDER}")


def strip_reasoning_and_fences(content: str) -> str:
    """Remove Qwen think blocks and optional Markdown YAML fences."""

    content = re.sub(r"<think>.*?</think>", "", content, flags=re.DOTALL).strip()
    fenced = re.fullmatch(
        r"```(?:yaml|yml)?\s*(.*?)\s*```",
        content,
        flags=re.DOTALL | re.IGNORECASE,
    )
    return fenced.group(1).strip() if fenced else content


def call_qwen_llm(
    system_prompt: str,
    user_prompt: str,
    model_name: str,
) -> str:
    """Invoke the OpenAI-compatible local Qwen endpoint."""

    if client is None:
        raise RuntimeError("The Qwen client is not configured.")

    request = {
        "model": model_name,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
        "temperature": 0.1,
        "max_tokens": MAX_COMPLETION_TOKENS,
        "stream": False,
    }

    try:
        response = client.chat.completions.create(
            **request,
            reasoning_effort="none",
        )
    except Exception:
        response = client.chat.completions.create(**request)

    first_choice, *_ = response.choices
    return strip_reasoning_and_fences(first_choice.message.content or "")


async def call_llm(
    system_prompt: str,
    user_prompt: str,
    model_name: str,
    copilot_session=None,
) -> str:
    """Invoke the configured LLM provider."""

    if LLM_PROVIDER == "qwen":
        return await asyncio.to_thread(
            call_qwen_llm,
            system_prompt,
            user_prompt,
            model_name,
        )

    if copilot_session is None:
        raise RuntimeError("The GitHub Copilot session has not been initialized.")

    response = await copilot_session.send_and_wait(
        f"{system_prompt}\n\n{user_prompt}"
    )
    if response is None or not response.data.content:
        raise RuntimeError("GitHub Copilot returned no content.")
    return strip_reasoning_and_fences(response.data.content)


