"""
CONTRACT & SPECIFICATION
======================
Script: toc_expander.py
Purpose: Filter sections from toc_ranked.txt with confidence >= --confidence_min,
         retrieve their full content from toc_enriched.json, and invoke an AI
         agent to:
           1) Link valid page footnotes and captions to the proper section.
           2) Resolve structural and semantic cross-references to other sections
              in toc_enriched.json (excluding listing/index sections).
         Outputs toc_complete.txt (all starting IDs + referenced IDs) and
         toc_enriched_resolved.json.

CLI Syntax:
  python toc_expander.py --ranked_toc <path_to_toc_ranked.txt>
                         --toc_enriched <path_to_toc_enriched.json>
                         --confidence_min <0.0-0.99>
                         [--prompt <path_to_prompt.txt>]
                         [--output <path_to_toc_complete.txt>]
                         [--concurrent <1-4>]

Arguments:
  --ranked_toc     (Required) Path to toc_ranked.txt generated by toc_ranker.py.
  --toc_enriched   (Required) Path to toc_enriched.json generated by Docling script.
  --confidence_min (Required) Minimum confidence threshold (float in [0.0, 0.99]).
  --prompt         (Optional) Path to system prompt file (default: prompt_expand.txt).
  --output         (Optional) Path to output file or directory (default: toc_complete.txt).
  --concurrent     (Optional) Max concurrent LLM requests, 1 to 4 (default: 1).

Outputs (saved in the target directory):
  1. toc_complete.txt           : Deduplicated list of starting + referenced section IDs
  2. toc_enriched_resolved.json : Subset of toc_enriched.json with validated footnotes
                                  and resolved cross-references
  3. <script_stem>_report.txt   : Console output log (overwritten at every run)
"""

import argparse
import asyncio
import io
import json
import os
import re
import sys
from contextlib import AsyncExitStack, contextmanager
from pathlib import Path


class Tee(io.TextIOBase):
    def __init__(self, console_stream, file_stream):
        self.console_stream = console_stream
        self.file_stream = file_stream

    @property
    def encoding(self):
        return getattr(self.console_stream, "encoding", "utf-8")

    def isatty(self) -> bool:
        return bool(
            hasattr(self.console_stream, "isatty")
            and self.console_stream.isatty()
        )

    def write(self, s: str) -> int:
        if not s:
            return 0
        self.console_stream.write(s)
        self.console_stream.flush()
        if not self.file_stream.closed:
            self.file_stream.write(s)
            self.file_stream.flush()
        return len(s)

    def flush(self) -> None:
        self.console_stream.flush()
        if not self.file_stream.closed:
            self.file_stream.flush()


@contextmanager
def tee_output_to_file(report_path: Path):
    report_path.parent.mkdir(parents=True, exist_ok=True)
    orig_stdout = sys.stdout
    orig_stderr = sys.stderr

    with report_path.open("w", encoding="utf-8") as report_file:
        sys.stdout = Tee(orig_stdout, report_file)
        sys.stderr = Tee(orig_stderr, report_file)
        try:
            yield report_path
        finally:
            sys.stdout = orig_stdout
            sys.stderr = orig_stderr


# --- 1. MODEL CONFIGURATION ---
LLM_PROVIDER = "qwen"  # "qwen" for local/OpenAI-compatible endpoint, "copilot" for GitHub Copilot

QWEN_BASE_URL = "http://localhost:1234/v1"
QWEN_MODEL_NAME = "qwen/qwen3.5-9b"
DEFAULT_PROMPT_FILE = "prompt_expand.txt"
DEFAULT_OUTPUT_FILE = "toc_complete.txt"

COPILOT_MODEL_NAME = "auto"
DEFAULT_MAX_CONCURRENT = 1
MAX_ALLOWED_CONCURRENT = 4

client = None

# Deterministic safeguard against listing/index sections in cross-references
LISTING_TITLE_PATTERN = re.compile(
    r"\b(?:table\s+of\s+contents|list\s+of\s+(?:figures|tables|examples)|glossary|index|abbreviations|acronyms|release\s+notes|revision\s+history)\b",
    re.IGNORECASE,
)

RANKED_LINE_PATTERN = re.compile(
    r"^\[(?P<id>[A-Za-z0-9_-]+)\]\s+(?P<title>.+?)\s+[—-]\s+confidence:\s*(?P<conf>[0-9]*\.?[0-9]+)\s*$"
)


def load_system_prompt(prompt_path: str) -> str:
    if not os.path.isfile(prompt_path):
        raise FileNotFoundError(f"Prompt file '{prompt_path}' does not exist.")
    with open(prompt_path, "r", encoding="utf-8") as f:
        system_prompt = f.read().strip()
    if not system_prompt:
        raise ValueError(f"Prompt file '{prompt_path}' is empty.")
    return system_prompt


def init_llm_client():
    global client
    if LLM_PROVIDER == "qwen":
        import httpx
        from openai import OpenAI

        client = OpenAI(
            base_url=QWEN_BASE_URL,
            api_key="lm-studio",
            timeout=600.0,
            http_client=httpx.Client(trust_env=False, timeout=600.0),
        )
        return QWEN_MODEL_NAME
    elif LLM_PROVIDER == "copilot":
        return COPILOT_MODEL_NAME
    else:
        raise ValueError(f"Unsupported LLM_PROVIDER: {LLM_PROVIDER}")


# --- 2. INPUT PARSING & SECTION MAP ---
def parse_ranked_toc(ranked_toc_path: str, confidence_min: float) -> list[dict]:
    selected = []
    with open(ranked_toc_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            match = RANKED_LINE_PATTERN.match(line)
            if not match:
                continue
            sec_id = match.group("id").strip()
            title = match.group("title").strip()
            conf = float(match.group("conf"))
            if conf >= confidence_min:
                selected.append({
                    "id": sec_id,
                    "title": title,
                    "confidence": conf,
                })
    return selected


def build_section_map_text(toc_enriched: dict) -> str:
    """Create a compact list of all valid sections in the document for cross-reference lookup."""
    lines = []
    for sec_id, data in toc_enriched.items():
        indent = "  " * max(0, data.get("level", 1) - 1)
        lines.append(f"{indent}[{sec_id}] {data.get('title', '')} (Page {data.get('page', '?')})")
    return "\n".join(lines)


# --- 3. LLM CALL & JSON PARSING ---
def build_user_prompt(section_data: dict, section_map_text: str) -> str:
    payload = {
        "id": section_data["id"],
        "title": section_data["title"],
        "page": section_data.get("page"),
        "text": section_data.get("text", []),
        "tables_md": section_data.get("tables_md", []),
    }
    return (
        "### DOCUMENT SECTION MAP\n"
        f"{section_map_text}\n\n"
        "### TARGET SECTION CONTENT\n"
        f"{json.dumps(payload, ensure_ascii=False, indent=2)}"
    )


def call_qwen_llm(system_prompt: str, user_prompt: str, model_name: str) -> str:
    if client is None:
        raise RuntimeError("The Qwen client is not configured.")

    try:
        response = client.chat.completions.create(
            model=model_name,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.1,
            max_tokens=1024,
            reasoning_effort="none",
            stream=False,
        )
    except Exception:
        response = client.chat.completions.create(
            model=model_name,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.1,
            max_tokens=1024,
            stream=False,
        )

    first_choice, *_ = response.choices
    content = first_choice.message.content or ""
    return re.sub(r"<think>.*?</think>", "", content, flags=re.DOTALL).strip()


async def call_llm(
    system_prompt: str,
    user_prompt: str,
    model_name: str,
    copilot_session=None,
) -> str:
    if LLM_PROVIDER == "qwen":
        return await asyncio.to_thread(call_qwen_llm, system_prompt, user_prompt, model_name)

    if copilot_session is None:
        raise RuntimeError("The GitHub Copilot session has not been initialized.")

    response = await copilot_session.send_and_wait(f"{system_prompt}\n\n{user_prompt}")
    if response is None or not response.data.content:
        raise RuntimeError("GitHub Copilot returned no content.")

    return re.sub(r"<think>.*?</think>", "", response.data.content, flags=re.DOTALL).strip()


def parse_agent_json(raw_content: str, expected_id: str, toc_enriched: dict) -> dict | None:
    cleaned = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw_content.strip(), flags=re.IGNORECASE)
    start = cleaned.find("{")
    end = cleaned.rfind("}")
    if start == -1 or end == -1 or end < start:
        return None

    try:
        parsed = json.loads(cleaned[start : end + 1])
    except json.JSONDecodeError:
        return None

    if not isinstance(parsed, dict):
        return None

    linked_footnotes = parsed.get("linked_footnotes", [])
    if not isinstance(linked_footnotes, list):
        linked_footnotes = []

    valid_refs = []
    raw_refs = parsed.get("referenced_sections", [])
    if isinstance(raw_refs, list):
        for ref in raw_refs:
            if not isinstance(ref, dict):
                continue
            target_id = str(ref.get("target_id", "")).strip()
            if target_id == expected_id or target_id not in toc_enriched:
                continue
            target_title = toc_enriched[target_id].get("title", "")
            # Exclude listing/index sections deterministically as a second safety layer
            if LISTING_TITLE_PATTERN.search(target_title):
                continue
            valid_refs.append({
                "target_id": target_id,
                "target_title": target_title,
                "reference_quote": str(ref.get("reference_quote", "")).strip(),
                "reference_type": str(ref.get("reference_type", "semantic")).strip(),
            })

    return {
        "section_id": expected_id,
        "linked_footnotes": linked_footnotes,
        "referenced_sections": valid_refs,
    }


# --- 4. MAIN PROCESSING PIPELINE ---
async def expand_sections(
    selected_items: list[dict],
    toc_enriched: dict,
    system_prompt: str,
    model_name: str,
    output_path: str,
    max_concurrent: int,
    copilot_sessions=None,
) -> None:
    section_map_text = build_section_map_text(toc_enriched)
    valid_items = [item for item in selected_items if item["id"] in toc_enriched]
    missing_in_json = [item["id"] for item in selected_items if item["id"] not in toc_enriched]

    if missing_in_json:
        print(f"Warning: {len(missing_in_json)} IDs not found in toc_enriched.json: {missing_in_json}")

    results_by_id: dict[str, dict] = {}

    async def process_batch(items: list[dict], attempt: int | None = None) -> dict[str, dict]:
        if not items:
            return {}
        worker_count = min(max_concurrent, len(items))
        batch_results: dict[str, dict] = {}

        async def worker(worker_idx: int) -> None:
            session = copilot_sessions[worker_idx] if copilot_sessions is not None else None
            for idx in range(worker_idx, len(items), worker_count):
                item = items[idx]
                sec_id = item["id"]
                if attempt is None:
                    print(f"  Analyzing section {idx + 1}/{len(items)} [{sec_id}] {item['title']}...")
                else:
                    print(f"  Retry {attempt}/2 for section [{sec_id}]: invalid JSON response.")

                user_prompt = build_user_prompt(toc_enriched[sec_id], section_map_text)
                raw_reply = await call_llm(system_prompt, user_prompt, model_name, session)
                parsed = parse_agent_json(raw_reply, sec_id, toc_enriched)
                if parsed is not None:
                    batch_results[sec_id] = parsed

        await asyncio.gather(*(worker(w) for w in range(worker_count)))
        return batch_results

    results_by_id.update(await process_batch(valid_items))

    for attempt in range(1, 3):
        pending = [item for item in valid_items if item["id"] not in results_by_id]
        if not pending:
            break
        results_by_id.update(await process_batch(pending, attempt))

    # Collect starting IDs + referenced IDs, preserving original document order
    starting_ids = {item["id"] for item in valid_items}
    referenced_by: dict[str, list[str]] = {}
    resolved_enriched: dict[str, dict] = {}

    for item in valid_items:
        sec_id = item["id"]
        sec_copy = dict(toc_enriched[sec_id])
        # Strip raw propagated footnote lines from text and attach verified ones
        sec_copy["text"] = [
            line for line in sec_copy.get("text", [])
            if not line.startswith("> [Footnote - Page ")
        ]
        agent_res = results_by_id.get(sec_id, {"linked_footnotes": [], "referenced_sections": []})
        sec_copy["linked_footnotes"] = agent_res["linked_footnotes"]
        sec_copy["referenced_sections"] = agent_res["referenced_sections"]
        resolved_enriched[sec_id] = sec_copy

        for ref in agent_res["referenced_sections"]:
            t_id = ref["target_id"]
            referenced_by.setdefault(t_id, [])
            if sec_id not in referenced_by[t_id]:
                referenced_by[t_id].append(sec_id)

    # Also include referenced sections in resolved_enriched if not already present
    for ref_id in referenced_by:
        if ref_id not in resolved_enriched and ref_id in toc_enriched:
            sec_copy = dict(toc_enriched[ref_id])
            sec_copy["text"] = [
                line for line in sec_copy.get("text", [])
                if not line.startswith("> [Footnote - Page ")
            ]
            resolved_enriched[ref_id] = sec_copy

    all_target_ids = starting_ids | set(referenced_by.keys())
    ordered_final_ids = [sec_id for sec_id in toc_enriched.keys() if sec_id in all_target_ids]

    # Resolve output file path
    if os.path.isdir(output_path):
        target_txt_path = os.path.join(output_path, DEFAULT_OUTPUT_FILE)
    else:
        target_txt_path = output_path

    out_dir = os.path.dirname(target_txt_path)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    complete_lines = []
    for sec_id in ordered_final_ids:
        title = toc_enriched[sec_id].get("title", "")
        page = toc_enriched[sec_id].get("page", "?")
        if sec_id in starting_ids and sec_id in referenced_by:
            tag = f"[SELECTED + REFERENCED by {', '.join(referenced_by[sec_id])}]"
        elif sec_id in starting_ids:
            tag = "[SELECTED]"
        else:
            tag = f"[REFERENCED by {', '.join(referenced_by[sec_id])}]"
        complete_lines.append(f"[{sec_id}] {title} (Page {page}) {tag}")

    with open(target_txt_path, "w", encoding="utf-8") as f:
        f.write("\n".join(complete_lines) + ("\n" if complete_lines else ""))

    resolved_json_path = (
        os.path.join(out_dir, "toc_enriched_resolved.json")
        if out_dir
        else "toc_enriched_resolved.json"
    )
    with open(resolved_json_path, "w", encoding="utf-8") as f:
        json.dump(resolved_enriched, f, indent=2, ensure_ascii=False)

    print(f"\nCompleted expansion: {len(starting_ids)} starting sections + "
          f"{len(set(referenced_by.keys()) - starting_ids)} newly referenced sections "
          f"= {len(ordered_final_ids)} total sections.")
    for line in complete_lines:
        print(f"  {line}")
    print(f"\nSaved complete TOC IDs to '{target_txt_path}'.")
    print(f"Saved resolved enriched JSON to '{resolved_json_path}'.")


# --- 5. CLI ENTRYPOINT ---
async def main():
    parser = argparse.ArgumentParser(
        description="Expand ranked TOC sections by resolving footnotes and cross-references via LLM."
    )
    parser.add_argument(
        "--ranked_toc",
        dest="ranked_toc_path",
        required=True,
        help="Path to toc_ranked.txt",
    )
    parser.add_argument(
        "--toc_enriched",
        dest="toc_enriched_path",
        required=True,
        help="Path to toc_enriched.json",
    )
    parser.add_argument(
        "--confidence_min",
        dest="confidence_min",
        type=float,
        required=True,
        help="Minimum confidence threshold (0.0 to 0.99)",
    )
    parser.add_argument(
        "--prompt",
        dest="prompt_path",
        default=DEFAULT_PROMPT_FILE,
        help=f"Path to system prompt file (default: {DEFAULT_PROMPT_FILE})",
    )
    parser.add_argument(
        "--output",
        dest="output_path",
        default=DEFAULT_OUTPUT_FILE,
        help=f"Path to output toc_complete.txt or directory (default: {DEFAULT_OUTPUT_FILE})",
    )
    parser.add_argument(
        "--concurrent",
        dest="max_concurrent",
        type=int,
        default=DEFAULT_MAX_CONCURRENT,
        help=f"Max concurrent LLM requests (1-{MAX_ALLOWED_CONCURRENT}, default: {DEFAULT_MAX_CONCURRENT})",
    )
    args = parser.parse_args()

    if not (0.0 <= args.confidence_min <= 0.99):
        print("Error: --confidence_min must be between 0.0 and 0.99.")
        sys.exit(1)

    if not (1 <= args.max_concurrent <= MAX_ALLOWED_CONCURRENT):
        print(f"Error: --concurrent must be between 1 and {MAX_ALLOWED_CONCURRENT}.")
        sys.exit(1)

    script_stem = Path(__file__).stem
    out_target = Path(args.output_path).expanduser().resolve()
    report_dir = out_target if out_target.is_dir() else out_target.parent
    report_path = report_dir / f"{script_stem}_report.txt"

    with tee_output_to_file(report_path):
        try:
            system_prompt = load_system_prompt(args.prompt_path)
            model_name = init_llm_client()
        except (FileNotFoundError, ValueError) as exc:
            print(f"Error: {exc}")
            sys.exit(1)

        if not os.path.isfile(args.ranked_toc_path):
            print(f"Error: Ranked TOC file '{args.ranked_toc_path}' does not exist.")
            sys.exit(1)

        if not os.path.isfile(args.toc_enriched_path):
            print(f"Error: Enriched TOC JSON '{args.toc_enriched_path}' does not exist.")
            sys.exit(1)

        with open(args.toc_enriched_path, "r", encoding="utf-8") as f:
            toc_enriched = json.load(f)

        selected_items = parse_ranked_toc(args.ranked_toc_path, args.confidence_min)
        if not selected_items:
            print(f"No sections found with confidence >= {args.confidence_min:.2f}.")
            sys.exit(0)

        print(
            f"Selected {len(selected_items)} sections with confidence >= {args.confidence_min:.2f}. "
            f"Processing with up to {args.max_concurrent} concurrent workers..."
        )

        if LLM_PROVIDER == "copilot":
            from copilot import CopilotClient

            async with CopilotClient() as copilot_client:
                async with AsyncExitStack() as session_stack:
                    session_count = min(args.max_concurrent, len(selected_items))
                    copilot_sessions = [
                        await session_stack.enter_async_context(
                            await copilot_client.create_session(model=model_name)
                        )
                        for _ in range(session_count)
                    ]
                    await expand_sections(
                        selected_items,
                        toc_enriched,
                        system_prompt,
                        model_name,
                        output_path=args.output_path,
                        max_concurrent=args.max_concurrent,
                        copilot_sessions=copilot_sessions,
                    )
        else:
            await expand_sections(
                selected_items,
                toc_enriched,
                system_prompt,
                model_name,
                output_path=args.output_path,
                max_concurrent=args.max_concurrent,
            )


if __name__ == "__main__":
    asyncio.run(main())