# CONCURRENT PROCESSING
# =============================================================================


async def process_sections(
    pairs: list[tuple[RankedSection, DocumentSection]],
    system_prompt: str,
    template_text: str,
    template_data: Any,
    model_name: str,
    output_dir: Path,
    max_concurrent: int,
    copilot_sessions=None,
) -> list[tuple[str, bool, str | None]]:
    """Process independent sections with a bounded worker pool."""

    if not pairs:
        return []

    worker_count = min(max_concurrent, len(pairs))
    results: list[tuple[str, bool, str | None] | None] = [None] * len(pairs)

    async def worker(worker_number: int) -> None:
        session = (
            copilot_sessions[worker_number]
            if copilot_sessions is not None
            else None
        )
        for index in range(worker_number, len(pairs), worker_count):
            ranked, section = pairs[index]
            results[index] = await generate_section_model(
                ranked,
                section,
                system_prompt,
                template_text,
                deepcopy(template_data),
                model_name,
                output_dir,
                session,
            )

    await asyncio.gather(*(worker(number) for number in range(worker_count)))
    return [result for result in results if result is not None]


