# Deterministic safeguard against listing/index sections in cross-references
LISTING_TITLE_PATTERN = re.compile(
    r"\b(?:table\s+of\s+contents|list\s+of\s+(?:figures|tables|examples)|glossary|index|abbreviations|acronyms|release\s+notes|revision\s+history|documentation\s+change\s+notification)\b",
    re.IGNORECASE,
)

# Matches output lines produced by toc2ranks.py:
# [SEC_0004]\t4. Peripherals\t(15 - 22)\t0.98
RANKED_LINE_PATTERN = re.compile(
    r"^\[(?P<id>[A-Za-z0-9_-]+)\]\t(?P<title>.+?)\t\((?P<pages>[^)]+)\)\t(?P<conf>[0-9]*\.?[0-9]+)\s*$"
)


def load_system_prompt(prompt_path: str) -> str:
    if not os.path.isfile(prompt_path):
        raise FileNotFoundError(f"Prompt file '{prompt_path}' does not exist.")
    with open(prompt_path, "r", encoding="utf-8") as f:
        system_prompt = f.read().strip()
    if not system_prompt:
        raise ValueError(f"Prompt file '{prompt_path}' is empty.")
    return system_prompt


