# --- 2. INPUT PARSING & DOCLING JSON SECTION RECONSTRUCTION ---
def parse_ranked_toc(ranked_toc_path: str) -> dict[str, dict]:
    """Parse all rows from toc_ranked.tsv keyed by section ID."""
    ranked_map: dict[str, dict] = {}
    with open(ranked_toc_path, "r", encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            if not stripped:
                continue
            match = RANKED_LINE_PATTERN.match(stripped)
            if not match:
                continue
            sec_id = match.group("id").strip()
            ranked_map[sec_id] = {
                "id": sec_id,
                "title": match.group("title").strip(),
                "pages": match.group("pages").strip(),
                "confidence": round(float(match.group("conf")), 2),
            }
    return ranked_map


def extract_sections_from_docling_json(json_path: str) -> dict[str, dict]:
    """Reconstruct SEC_XXXX sections from Docling JSON matching pdf2toc.py traversal."""
    doc = DoclingDocument.load_from_json(json_path)

    bullet_pattern = re.compile(r"^[\u00b7\u2022\-\*\•\·]\s+")
    noise_heading_pattern = re.compile(
        r"^(?:Where:|(?:Notes?|Notices?|Caution|Warning|Important)\s*[:：]|(?:Table\s+\d+\.|Figure\s+\d+\.|Equation\s+\d+:)\b)",
        re.IGNORECASE,
    )

    def clean_heading_text(raw_title: str) -> str:
        cleaned = re.sub(r"^[^\w\s\(\)\[\]]+\s*", "", raw_title.strip())
        return cleaned.strip()

    # 1. Collect footnotes and captions per page
    footnotes_by_page: dict[int, list[str]] = {}
    captions_by_page: dict[int, list[str]] = {}

    for item, _ in doc.iterate_items(
        included_content_layers={ContentLayer.BODY, ContentLayer.FURNITURE}
    ):
        label = getattr(item, "label", None)
        page_no = getattr(item.prov[0], "page_no", None) if getattr(item, "prov", None) else None
        if page_no is None or not hasattr(item, "text"):
            continue
        item_text = item.text.strip()
        if not item_text:
            continue

        if label == DocItemLabel.FOOTNOTE:
            footnotes_by_page.setdefault(page_no, [])
            if item_text not in footnotes_by_page[page_no]:
                footnotes_by_page[page_no].append(item_text)
        elif label == DocItemLabel.CAPTION:
            captions_by_page.setdefault(page_no, [])
            if item_text not in captions_by_page[page_no]:
                captions_by_page[page_no].append(item_text)

    mapped_sections: dict[str, dict] = {}
    section_pages: dict[str, set[int]] = {}
    current_section: dict | None = None
    id_counter = 0

    def create_section(title: str, level: int, page: int | str) -> dict:
        nonlocal id_counter
        sec_id = f"SEC_{id_counter:04d}"
        id_counter += 1
        section_pages[sec_id] = set()
        if isinstance(page, int):
            section_pages[sec_id].add(page)
        return {
            "id": sec_id,
            "level": level,
            "title": title,
            "page": page,
            "text": [],
            "tables_md": [],
            "images": [],
            "page_footnotes": [],
            "page_captions": [],
        }

    def track_page(sec: dict, page: int | str) -> None:
        if isinstance(page, int):
            section_pages[sec["id"]].add(page)

    # 2. Traverse main body identical to pdf2toc.py
    for item, tree_level in doc.iterate_items(included_content_layers={ContentLayer.BODY}):
        if getattr(item, "label", None) == DocItemLabel.FOOTNOTE:
            continue

        page = getattr(item.prov[0], "page_no", "?") if getattr(item, "prov", None) else "?"

        if isinstance(item, SectionHeaderItem):
            raw_text = item.text.strip()

            if bullet_pattern.match(raw_text):
                if current_section is None:
                    current_section = create_section("Preamble / Initial Content", 1, page)
                track_page(current_section, page)
                bullet_label = bullet_pattern.sub("", raw_text).strip()
                if bullet_label:
                    current_section["text"].append(f"- **{bullet_label}**")
                continue

            clean_title = clean_heading_text(raw_text)

            if noise_heading_pattern.match(clean_title):
                if current_section is None:
                    current_section = create_section("Preamble / Initial Content", 1, page)
                track_page(current_section, page)
                current_section["text"].append(f"**{clean_title}**")
                continue

            if current_section is not None:
                mapped_sections[current_section["id"]] = current_section

            raw_level = getattr(item, "level", None)
            heading_level = max(1, raw_level if raw_level is not None else tree_level)
            current_section = create_section(clean_title, heading_level, page)
        else:
            if current_section is None:
                current_section = create_section("Preamble / Initial Content", 1, page)

            track_page(current_section, page)

            if isinstance(item, TextItem):
                current_section["text"].append(item.text)
            elif isinstance(item, TableItem):
                current_section["tables_md"].append(item.export_to_markdown(doc))
            elif isinstance(item, PictureItem):
                uri = str(item.image.uri) if (item.image and item.image.uri) else None
                current_section["images"].append({"uri": uri})

    if current_section is not None:
        mapped_sections[current_section["id"]] = current_section

    # 3. Attach candidate page footnotes, captions, and compute page ranges
    sec_ids = list(mapped_sections.keys())
    for idx, sec_id in enumerate(sec_ids):
        data = mapped_sections[sec_id]
        touched = sorted(section_pages.get(sec_id, set()))
        data["touched_pages"] = touched

        for p in touched:
            for fn in footnotes_by_page.get(p, []):
                data["page_footnotes"].append({"page": p, "text": fn})
            for cap in captions_by_page.get(p, []):
                data["page_captions"].append({"page": p, "text": cap})

        if touched:
            start_p, end_p = touched[0], touched[-1]
            data["pages_str"] = f"{start_p} - {end_p}" if start_p != end_p else str(start_p)
        else:
            start_p = data["page"] if isinstance(data["page"], int) else 0
            next_p = (
                mapped_sections[sec_ids[idx + 1]]["page"]
                if idx + 1 < len(sec_ids) and isinstance(mapped_sections[sec_ids[idx + 1]]["page"], int)
                else start_p
            )
            end_p = max(start_p, next_p)
            data["pages_str"] = (
                f"{start_p} - {end_p}" if start_p != end_p else str(start_p)
            ) if start_p else "?"

    return mapped_sections


def build_section_map_text(sections_map: dict[str, dict]) -> str:
    """Create a compact list of all valid sections in the document for cross-reference lookup."""
    lines = []
    for sec_id, data in sections_map.items():
        indent = "  " * max(0, data.get("level", 1) - 1)
        lines.append(f"{indent}[{sec_id}] {data.get('title', '')} (Page {data.get('page', '?')})")
    return "\n".join(lines)


# --- 3. LLM CALL & RESPONSE PARSING ---
def build_user_prompt(section_data: dict, section_map_text: str) -> str:
    payload = {
        "id": section_data["id"],
        "title": section_data["title"],
        "page": section_data.get("page"),
        "text": section_data.get("text", []),
        "tables_md": section_data.get("tables_md", []),
        "candidate_page_footnotes": section_data.get("page_footnotes", []),
        "candidate_page_captions": section_data.get("page_captions", []),
    }
    return (
        "### DOCUMENT SECTION MAP\n"
        f"{section_map_text}\n\n"
        "### TARGET SECTION CONTENT\n"
        f"{json.dumps(payload, ensure_ascii=False, indent=2)}"
    )


def call_qwen_llm(system_prompt: str, user_prompt: str, model_name: str) -> str:
    if client is None:
        raise RuntimeError("The Qwen client is not configured.")

    try:
        response = client.chat.completions.create(
            model=model_name,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.1,
            max_tokens=1024,
            reasoning_effort="none",
            stream=False,
        )
    except Exception:
        response = client.chat.completions.create(
            model=model_name,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.1,
            max_tokens=1024,
            stream=False,
        )

    first_choice, *_ = response.choices
    content = first_choice.message.content or ""
    return re.sub(r"<think>.*?</think>", "", content, flags=re.DOTALL).strip()


async def call_llm(
    system_prompt: str,
    user_prompt: str,
    model_name: str,
    copilot_session=None,
) -> str:
    if LLM_PROVIDER == "qwen":
        return await asyncio.to_thread(call_qwen_llm, system_prompt, user_prompt, model_name)

    if copilot_session is None:
        raise RuntimeError("The GitHub Copilot session has not been initialized.")

    response = await copilot_session.send_and_wait(f"{system_prompt}\n\n{user_prompt}")
    if response is None or not response.data.content:
        raise RuntimeError("GitHub Copilot returned no content.")

    return re.sub(r"<think>.*?</think>", "", response.data.content, flags=re.DOTALL).strip()


def _resolve_target_id(raw_id: str, sections_map: dict[str, dict]) -> str | None:
    if raw_id in sections_map:
        return raw_id
    for known_id in sections_map:
        if known_id.endswith(f"_{raw_id}") or known_id.lstrip("0") == raw_id.lstrip("0"):
            return known_id
    return None


def parse_agent_json(
    raw_content: str,
    expected_id: str,
    sections_map: dict[str, dict],
) -> dict | None:
    cleaned = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw_content.strip(), flags=re.IGNORECASE)
    start = cleaned.find("{")
    end = cleaned.rfind("}")
    if start == -1 or end == -1 or end < start:
        return None

    try:
        parsed = json.loads(cleaned[start : end + 1])
    except json.JSONDecodeError:
        return None

    if not isinstance(parsed, dict):
        return None

    linked_footnotes = parsed.get("linked_footnotes", [])
    if not isinstance(linked_footnotes, list):
        linked_footnotes = []

    linked_captions = parsed.get("linked_captions", [])
    if not isinstance(linked_captions, list):
        linked_captions = []

    valid_refs = []
    raw_refs = parsed.get("referenced_sections", [])
    if isinstance(raw_refs, list):
        for ref in raw_refs:
            if not isinstance(ref, dict):
                continue
            raw_target_id = str(ref.get("target_id") or ref.get("id") or "").strip()
            target_id = _resolve_target_id(raw_target_id, sections_map)
            if target_id is None or target_id == expected_id:
                continue

            target_title = sections_map[target_id].get("title", "")
            if LISTING_TITLE_PATTERN.search(target_title):
                continue

            # Parse optional confidence returned by the agent for the referenced section
            agent_conf: float | None = None
            raw_conf = ref.get("confidence")
            if raw_conf is not None:
                try:
                    agent_conf = round(max(0.0, min(1.0, float(raw_conf))), 2)
                except (ValueError, TypeError):
                    agent_conf = None

            valid_refs.append({
                "target_id": target_id,
                "target_title": target_title,
                "reference_quote": str(ref.get("reference_quote", "")).strip(),
                "reference_type": str(ref.get("reference_type", "semantic")).strip().lower(),
                "agent_confidence": agent_conf,
            })

    return {
        "section_id": expected_id,
        "linked_footnotes": linked_footnotes,
        "linked_captions": linked_captions,
        "referenced_sections": valid_refs,
    }


def compute_referenced_confidence(
    ref_id: str,
    ranked_map: dict[str, dict],
    referring_sources: list[dict],
) -> float:
    """
    Compute confidence for a referenced section:
      1) Use its explicit score from toc_ranked.tsv if available.
      2) Otherwise use the max confidence provided by the agent for that reference.
      3) Fallback: derive a decayed score from the highest-confidence referring section.
    """
    if ref_id in ranked_map:
        return ranked_map[ref_id]["confidence"]

    agent_scores = [
        src["agent_confidence"]
        for src in referring_sources
        if src.get("agent_confidence") is not None
    ]
    if agent_scores:
        return round(max(agent_scores), 2)

    # Structural references carry higher inheritance weight than loose semantic ones
    derived_scores = []
    for src in referring_sources:
        factor = 0.85 if "struct" in src.get("reference_type", "") else 0.75
        derived_scores.append(src["source_confidence"] * factor)

    return round(max(derived_scores), 2) if derived_scores else 0.00


# --- 4. MAIN PROCESSING PIPELINE ---
async def expand_sections(
    selected_items: list[dict],
    ranked_map: dict[str, dict],
    sections_map: dict[str, dict],
    system_prompt: str,
    model_name: str,
    output_path: str,
    ranked_toc_path: str,
    max_concurrent: int,
    copilot_sessions=None,
) -> None:
    section_map_text = build_section_map_text(sections_map)
    valid_items = [item for item in selected_items if item["id"] in sections_map]
    missing_in_json = [item["id"] for item in selected_items if item["id"] not in sections_map]

    if missing_in_json:
        print(f"Warning: {len(missing_in_json)} IDs not found in Docling JSON: {missing_in_json}")

    results_by_id: dict[str, dict] = {}

    async def process_batch(items: list[dict], attempt: int | None = None) -> dict[str, dict]:
        if not items:
            return {}
        worker_count = min(max_concurrent, len(items))
        batch_results: dict[str, dict] = {}

        async def worker(worker_idx: int) -> None:
            session = copilot_sessions[worker_idx] if copilot_sessions is not None else None
            for idx in range(worker_idx, len(items), worker_count):
                item = items[idx]
                sec_id = item["id"]
                if attempt is None:
                    print(f"  Analyzing section {idx + 1}/{len(items)} [{sec_id}] {item['title']}...")
                else:
                    print(f"  Retry {attempt}/2 for section [{sec_id}]: invalid JSON response.")

                user_prompt = build_user_prompt(sections_map[sec_id], section_map_text)
                raw_reply = await call_llm(system_prompt, user_prompt, model_name, session)
                parsed = parse_agent_json(raw_reply, sec_id, sections_map)
                if parsed is not None:
                    batch_results[sec_id] = parsed

        await asyncio.gather(*(worker(w) for w in range(worker_count)))
        return batch_results

    results_by_id.update(await process_batch(valid_items))

    for attempt in range(1, 3):
        pending = [item for item in valid_items if item["id"] not in results_by_id]
        if not pending:
            break
        results_by_id.update(await process_batch(pending, attempt))

    # Collect starting IDs + referenced IDs, preserving original document order
    starting_ids = {item["id"] for item in valid_items}
    referenced_by: dict[str, list[dict]] = {}

    for item in valid_items:
        sec_id = item["id"]
        agent_res = results_by_id.get(
            sec_id,
            {"linked_footnotes": [], "linked_captions": [], "referenced_sections": []},
        )
        for ref in agent_res["referenced_sections"]:
            t_id = ref["target_id"]
            referenced_by.setdefault(t_id, [])
            if not any(entry["source_id"] == sec_id for entry in referenced_by[t_id]):
                referenced_by[t_id].append({
                    "source_id": sec_id,
                    "source_confidence": item["confidence"],
                    "reference_type": ref["reference_type"],
                    "agent_confidence": ref["agent_confidence"],
                })

    all_target_ids = starting_ids | set(referenced_by.keys())
    ordered_final_ids = [sec_id for sec_id in sections_map.keys() if sec_id in all_target_ids]

    # Resolve output file path (preserving _pMIN-MAX suffix when --output is a directory)
    if os.path.isdir(output_path):
        range_match = re.search(r"(_p\d+-\d+)$", Path(ranked_toc_path).stem)
        suffix = range_match.group(1) if range_match else ""
        target_tsv_path = os.path.join(output_path, f"chunks{suffix}.tsv")
    else:
        target_tsv_path = output_path

    out_dir = os.path.dirname(target_tsv_path)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    complete_lines = []
    for sec_id in ordered_final_ids:
        sec_info = sections_map[sec_id]
        ranked_info = ranked_map.get(sec_id)

        title = ranked_info["title"] if ranked_info else sec_info.get("title", "")
        pages = ranked_info["pages"] if ranked_info else sec_info.get("pages_str", "?")

        if sec_id in starting_ids:
            conf = ranked_info["confidence"] if ranked_info else 0.00
        else:
            conf = compute_referenced_confidence(sec_id, ranked_map, referenced_by[sec_id])

        ref_sources = [entry["source_id"] for entry in referenced_by.get(sec_id, [])]
        if sec_id in starting_ids and ref_sources:
            tag = f"[SELECTED + REFERENCED by {', '.join(ref_sources)}]"
        elif sec_id in starting_ids:
            tag = "[SELECTED]"
        else:
            tag = f"[REFERENCED by {', '.join(ref_sources)}]"

        complete_lines.append(f"[{sec_id}]\t{title}\t({pages})\t{conf:.2f}\t{tag}")

    with open(target_tsv_path, "w", encoding="utf-8") as f:
        f.write("\n".join(complete_lines) + ("\n" if complete_lines else ""))

    newly_referenced_count = len(set(referenced_by.keys()) - starting_ids)
    print(
        f"\nCompleted expansion: {len(starting_ids)} starting sections + "
        f"{newly_referenced_count} newly referenced sections "
        f"= {len(ordered_final_ids)} total sections."
    )
    for line in complete_lines:
        print(f"  {line}")
    print(f"\nSaved chunks TSV to '{target_tsv_path}'.")


