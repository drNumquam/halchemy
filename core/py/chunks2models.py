async def async_main() -> int:
    args = build_argument_parser().parse_args()

    if not 0.0 <= args.confidence_min <= 1.0:
        print("Error: --confidence_min must be between 0.00 and 1.00.")
        return 2
    if not 1 <= args.max_concurrent <= MAX_ALLOWED_CONCURRENT:
        print(
            "Error: --concurrent must be between 1 and "
            f"{MAX_ALLOWED_CONCURRENT}."
        )
        return 2

    output_dir = Path(args.output_dir).expanduser().resolve()
    if output_dir.exists() and not output_dir.is_dir():
        print(f"Error: --output is not a folder: {output_dir}")
        return 2
    output_dir.mkdir(parents=True, exist_ok=True)

    report_path = output_dir / f"{Path(__file__).stem}_report.txt"

    with tee_output_to_file(report_path):
        try:
            json_path = require_file(args.json_path, "Docling JSON file")
            ranks_path = require_file(args.ranks_path, "Ranked TSV file")
            prompt_path = require_file(args.prompt_path, "Prompt file")
            template_path = require_file(args.template_path, "YAML template")

            system_prompt = load_nonempty_text(prompt_path, "Prompt file")
            template_text, template_data = load_yaml_template(template_path)
            document = load_json_document(json_path)
            ranked, total_ranked = load_ranked_sections(
                ranks_path,
                args.confidence_min,
            )
            document_sections = reconstruct_sections(document)
            matched, missing = match_ranked_sections(ranked, document_sections)
            model_name = init_llm_client()
        except (FileNotFoundError, ValueError, OSError) as exc:
            print(f"Error: {exc}")
            return 1

        print("=" * 79)
        print("chunks2models.py")
        print("=" * 79)
        print(f"JSON             : {json_path}")
        print(f"RANKS            : {ranks_path}")
        print(f"PROMPT           : {prompt_path}")
        print(f"TEMPLATE         : {template_path}")
        print(f"OUTPUT           : {output_dir}")
        print(f"CONFIDENCE_MIN   : {args.confidence_min:.2f}")
        print(f"CONCURRENT       : {args.max_concurrent}")
        print(f"LLM_PROVIDER     : {LLM_PROVIDER}")
        print(f"MODEL            : {model_name}")
        print(f"Ranked rows      : {total_ranked}")
        print(f"Selected rows    : {len(ranked)}")
        print(f"Docling sections : {len(document_sections)}")
        print(f"Matched sections : {len(matched)}")
        print(f"Missing sections : {len(missing)}")

        for ranked_section in missing:
            print(
                f"WARNING: section not found in Docling JSON: "
                f"[{ranked_section.section_id}] {ranked_section.title}"
            )

        if not matched:
            print("Error: no selected ranked sections matched the Docling document.")
            return 1

        print(
            f"\nSending one request per section with up to "
            f"{args.max_concurrent} concurrent workers...\n"
        )

        if LLM_PROVIDER == "copilot":
            from copilot import CopilotClient

            async with CopilotClient() as copilot_client:
                async with AsyncExitStack() as session_stack:
                    session_count = min(args.max_concurrent, len(matched))
                    sessions = [
                        await session_stack.enter_async_context(
                            await copilot_client.create_session(model=model_name)
                        )
                        for _ in range(session_count)
                    ]
                    results = await process_sections(
                        matched,
                        system_prompt,
                        template_text,
                        template_data,
                        model_name,
                        output_dir,
                        args.max_concurrent,
                        copilot_sessions=sessions,
                    )
        else:
            results = await process_sections(
                matched,
                system_prompt,
                template_text,
                template_data,
                model_name,
                output_dir,
                args.max_concurrent,
            )

        succeeded = sum(1 for _, success, _ in results if success)
        failed = len(results) - succeeded

        print("\n" + "=" * 79)
        print("EXECUTION SUMMARY")
        print("=" * 79)
        print(f"Ranked rows                 : {total_ranked}")
        print(f"Selected by confidence      : {len(ranked)}")
        print(f"Matched and processed       : {len(results)}")
        print(f"Successful YAML generations : {succeeded}")
        print(f"Failed YAML generations     : {failed}")
        print(f"Unmatched selected sections : {len(missing)}")
        print(f"Output folder               : {output_dir}")
        print(f"Report file                 : {report_path}")

        return 0 if failed == 0 and not missing else 1


def main() -> None:
    try:
        exit_code = asyncio.run(async_main())
    except KeyboardInterrupt:
        print("\nExecution interrupted by the user.", file=sys.stderr)
        exit_code = 130
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
