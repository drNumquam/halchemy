def require_file(raw_path: str, description: str) -> Path:
    """Resolve and validate a required file path."""

    path = Path(raw_path).expanduser().resolve()
    if not path.exists():
        raise FileNotFoundError(f"{description} does not exist: {path}")
    if not path.is_file():
        raise ValueError(f"{description} is not a file: {path}")
    return path


def load_nonempty_text(path: Path, description: str) -> str:
    """Read a required non-empty UTF-8 text file."""

    content = path.read_text(encoding="utf-8").strip()
    if not content:
        raise ValueError(f"{description} is empty: {path}")
    return content


def load_json_document(path: Path) -> dict[str, Any]:
    """Load and minimally validate a raw Docling JSON document."""

    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"Invalid JSON in '{path}': {exc}") from exc

    if not isinstance(document, dict):
        raise ValueError("The Docling JSON root must be an object.")
    if "body" not in document or "texts" not in document:
        raise ValueError(
            "The JSON does not look like a raw Docling document: "
            "required keys 'body' and 'texts' are missing."
        )
    return document


def load_yaml_template(path: Path) -> tuple[str, Any]:
    """Load the template as text and parsed YAML."""

    template_text = load_nonempty_text(path, "YAML template")
    try:
        template_data = yaml.safe_load(template_text)
    except yaml.YAMLError as exc:
        raise ValueError(f"Invalid YAML template '{path}': {exc}") from exc

    if template_data is None:
        raise ValueError(f"YAML template is empty: {path}")
    return template_text, template_data


