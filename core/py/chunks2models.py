"""
CONTRACT & SPECIFICATION
========================
Script: chunks2models.py

Purpose:
    Read a raw Docling JSON document, a ranked TOC TSV generated by
    toc2ranks.py, a system prompt, and a YAML template. For every ranked
    section whose confidence is greater than or equal to --confidence_min,
    reconstruct the corresponding section from the Docling document, build a
    Markdown chunk, invoke the configured AI provider, validate the returned
    YAML, and save one compiled YAML model per section.

CLI syntax:
    python chunks2models.py \
        --json <document.json> \
        --ranks <toc_ranked.tsv> \
        --prompt <prompt.txt> \
        --template <template.yaml> \
        --confidence_min <0.00-1.00> \
        --output <folder> \
        [--concurrent <1-4>]

Required arguments:
    --json             Raw Docling JSON generated by pdf2toc.py.
    --ranks            Ranked TSV generated by toc2ranks.py.
    --prompt           System prompt used by the AI agent.
    --template         YAML template to populate.
    --confidence_min   Inclusive confidence threshold in the range 0.00-1.00.
    --output           Output folder. It is created when missing and may
                       already exist. Existing YAML files are overwritten.

Optional arguments:
    --concurrent       Maximum concurrent LLM requests, from 1 to 4.
                       Default: 1.

Outputs:
    <output>/<SEC_ID>.yaml
        One populated YAML file for every successfully processed ranked
        section.

    <output>/chunks2models_report.txt
        Complete copy of stdout and stderr. The report is overwritten at every
        execution.

Dependencies:
    Standard library plus:
        pyyaml
        openai and httpx, when LLM_PROVIDER == "qwen"
        copilot, when LLM_PROVIDER == "copilot"

Design notes:
    - The ranked TSV is authoritative for section ID, title, pages and score.
    - Section IDs are reconstructed using the same sequential SEC_0000 rule
      and heading filtering used by pdf2toc.py.
    - Each selected section is sent to the model independently.
    - AI output is accepted only when it is valid YAML and its root structure
      is compatible with the supplied template.
"""

